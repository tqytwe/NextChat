type WidenMobileText<T> = T extends (...args: infer Args) => infer Result
  ? (...args: Args) => Result
  : T extends readonly unknown[]
  ? T
  : T extends string
  ? string
  : T extends object
  ? { [K in keyof T]: WidenMobileText<T[K]> }
  : T;

type DeepPartialMobileText<T> = T extends (...args: any[]) => any
  ? T
  : T extends readonly unknown[]
  ? T
  : T extends object
  ? { [K in keyof T]?: DeepPartialMobileText<T[K]> }
  : T;

type ManagedMobileTextOverrides = DeepPartialMobileText<
  WidenMobileText<typeof MANAGED_MOBILE_TEXT_BASE.en>
>;

function isPlainTextObject(value: unknown): value is Record<string, unknown> {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    typeof value !== "function"
  );
}

function mergeManagedMobileText<T extends object>(
  base: T,
  overrides: DeepPartialMobileText<WidenMobileText<T>>,
): WidenMobileText<T> {
  const output: Record<string, unknown> = {
    ...(base as Record<string, unknown>),
  };
  for (const [key, overrideValue] of Object.entries(
    overrides as Record<string, unknown>,
  )) {
    if (overrideValue === undefined) continue;
    const baseValue = output[key];
    output[key] =
      isPlainTextObject(baseValue) && isPlainTextObject(overrideValue)
        ? mergeManagedMobileText(baseValue, overrideValue)
        : overrideValue;
  }
  return output as WidenMobileText<T>;
}

