export type ManagedMobileLocale = "cn" | "en" | "jp" | "ko";

export const MANAGED_MOBILE_LOCALE_STORAGE_KEY =
  "jisudeng-managed-mobile-locale";

function storedManagedMobileLocale(): ManagedMobileLocale | null {
  if (typeof localStorage === "undefined") return null;
  const value = localStorage.getItem(MANAGED_MOBILE_LOCALE_STORAGE_KEY);
  return value === "cn" || value === "en" || value === "jp" || value === "ko"
    ? value
    : null;
}

export function setManagedMobileLocale(locale: ManagedMobileLocale | null) {
  if (typeof localStorage === "undefined") return;
  if (locale) {
    localStorage.setItem(MANAGED_MOBILE_LOCALE_STORAGE_KEY, locale);
  } else {
    localStorage.removeItem(MANAGED_MOBILE_LOCALE_STORAGE_KEY);
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(new Event("jisudeng:mobile-locale-change"));
  }
}

