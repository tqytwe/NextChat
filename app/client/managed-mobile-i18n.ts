type WidenMobileText<T> = T extends (...args: infer Args) => infer Result
  ? (...args: Args) => Result
  : T extends string
  ? string
  : T extends object
  ? { [K in keyof T]: WidenMobileText<T[K]> }
  : T;

export type ManagedMobileText = WidenMobileText<typeof MANAGED_MOBILE_TEXT.cn>;

export function getManagedMobileLocale(): ManagedMobileLocale {
  if (typeof navigator === "undefined") {
    return "cn";
  }

  const languages =
    navigator.languages && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language];
  const primary = (languages.find(Boolean) || "").toLowerCase();
  return primary.startsWith("en") ? "en" : "cn";
}

export function getManagedMobileText(
  locale: ManagedMobileLocale = getManagedMobileLocale(),
): ManagedMobileText {
  return MANAGED_MOBILE_TEXT[locale] as ManagedMobileText;
}

export function localizeManagedMobileError(input: {
  message?: string;
  status?: number;
  path?: string;
}) {
  const text = getManagedMobileText();
  const raw = (input.message || "").trim();
  const normalized = raw.toLowerCase();

  if (
    input.status === 404 &&
    input.path?.includes("/api/v1/auth/mobile/login")
  ) {
    return text.errors.appLoginNotSupported;
  }
  if (
    input.status === 404 ||
    /404|not found|page not found|不存在/.test(normalized)
  ) {
    return text.errors.notFound;
  }
  if (/failed to fetch|network|网络/.test(normalized)) {
    return text.errors.networkFailed;
  }
  if (/cancelled|canceled|已取消/.test(normalized)) {
    return text.errors.requestCancelled;
  }
  if (
    /invalid_verify_code|invalid_reset_token|verification code is invalid|验证码无效|验证码.*过期/.test(
      normalized,
    )
  ) {
    return text.errors.invalidVerifyCode;
  }
  if (/verify_code_too_frequent|too frequent|发送过于频繁/.test(normalized)) {
    return text.errors.verifyCodeTooFrequent;
  }
  if (
    /mobile_feedback_too_many_screenshots|too many screenshots/.test(normalized)
  ) {
    return text.errors.feedbackTooManyScreenshots;
  }
  if (
    /mobile_feedback_unavailable|asset_storage_unavailable|feedback storage|反馈服务/.test(
      normalized,
    )
  ) {
    return text.errors.feedbackUnavailable;
  }
  if (/mobile_feedback_invalid|invalid feedback/.test(normalized)) {
    return text.errors.feedbackInvalid;
  }
  if (
    /payment_gateway|payment gateway|payment_provider|provider_misconfigured|method_not_configured|no_available_instance|easypay|xunhupay|wxpay|alipay|支付通道|支付网关|支付方式/.test(
      normalized,
    )
  ) {
    return text.errors.paymentGatewayReason(raw || text.errors.paymentFailed);
  }
  if (
    /invalid_return_url|return_url|same host|browser origin/.test(normalized)
  ) {
    return text.errors.paymentReturnUrlInvalid;
  }
  if (
    /permission denied|not available|camera|speech|microphone|权限/.test(
      normalized,
    )
  ) {
    return text.errors.permissionDenied;
  }
  if (/turnstile|安全验证/.test(normalized)) {
    return text.errors.turnstileFailed;
  }
  if (
    /invalid credentials|incorrect|密码不正确|邮箱或密码错误|凭据/.test(
      normalized,
    )
  ) {
    return text.errors.invalidCredentials;
  }
  if (input.status === 401 || /unauthorized|登录状态|token/.test(normalized)) {
    return text.errors.unauthorized;
  }
  if (
    input.status === 503 ||
    /service unavailable|temporarily unavailable|服务器暂时不可用/.test(
      normalized,
    )
  ) {
    return text.errors.serviceUnavailable;
  }
  if (
    input.status === 502 ||
    /bad gateway|cloudflare|origin server|retry_after|upstream|overloaded/.test(
      normalized,
    )
  ) {
    return text.errors.upstreamBusy;
  }
  if (
    /image generation is not enabled|image_studio_image_not_allowed|未开启图片生成/.test(
      normalized,
    )
  ) {
    return text.errors.imageNotAllowed;
  }
  if (/style.*not supported|style_not_supported|风格参数/.test(normalized)) {
    return text.errors.imageStyleUnsupported;
  }
  if (/no image models|no available image|暂无可用图片模型/.test(normalized)) {
    return text.errors.noImageModels;
  }
  if (raw) return raw;
  if (input.status) return text.errors.requestFailed(input.status);
  return text.errors.serviceUnavailable;
}
